"""Render every edition into a static site (ADR 0001, 0002).

The build is deterministic and idempotent: same inputs, same bytes out.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import shutil
from dataclasses import dataclass
from pathlib import Path

from jinja2 import Environment, PackageLoader, StrictUndefined
from markupsafe import escape
from pydantic import BaseModel, ConfigDict

from timeleaf.models import Edition

STATIC = Path(__file__).parent / "static"
MARKER = ".timeleaf-build"


class SiteConfig(BaseModel):
    """``config/site.json``: the site, not any one reader. The paper's name is in the reader's reader.json."""

    model_config = ConfigDict(extra="forbid")
    base_url: str
    site_name: str
    description: str
    language: str = "en"
    indexable: bool = True
    feedback_form_action: str | None = None
    primary_reader: str | None = None  # whose paper is built at the site root when there are several

    def url(self, path: str) -> str:
        return self.base_url.rstrip("/") + path


class PaperSite(SiteConfig):
    """What the templates see as ``site``: the site config plus the name of the paper being built."""

    publication: str


@dataclass(frozen=True)
class Page:
    path: str  # site path, e.g. "/editions/2026-11-27/"
    file: str  # output file relative to the build root


def edition_path(e: Edition) -> str:
    return f"/editions/{e.date.isoformat()}/"


def load_editions(directory: Path) -> list[Edition]:
    eds = [
        Edition.model_validate_json(p.read_text(encoding="utf-8")) for p in sorted(directory.glob("*.json"))
    ]
    eds.sort(key=lambda e: e.date)
    numbers = [e.number for e in eds]
    if len(set(numbers)) != len(numbers):
        raise ValueError(f"duplicate edition numbers in {directory}: {numbers}")
    return eds


def _env() -> Environment:
    env = Environment(
        loader=PackageLoader("timeleaf.build", "templates"),
        autoescape=True,
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    env.filters["longdate"] = lambda d: f"{d.day} {d:%B %Y}"
    return env


def _asset_version() -> str:
    """Cache-busting token for style.css. Line endings are normalised so every OS builds the same bytes."""
    css = (STATIC / "style.css").read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(css).hexdigest()[:10]


def _feed_html(e: Edition) -> str:
    parts = [f"<p>{escape(e.lede)}</p>"]
    for s in e.sections:
        parts.append(f"<h3>{escape(s.title)}</h3><ul>")
        for i in s.items:
            title = f'<a href="{escape(i.url)}">{escape(i.title)}</a>' if i.url else escape(i.title)
            parts.append(f"<li>{title}</li>")
        parts.append("</ul>")
    return "".join(parts)


def _prepare_out(out: Path) -> None:
    """Only ever delete a directory this tool created."""
    if out.exists():
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise FileExistsError(
                f"{out} is not empty and was not created by `timeleaf build`; refusing to clear it"
            )
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by timeleaf build; safe to delete\n", encoding="utf-8")


def build(
    editions_dir: Path, out: Path, site: SiteConfig, today: dt.date | None = None, *, paper_name: str
) -> list[Page]:
    """Render one reader's paper at the root of ``out``. Only that reader's editions are read."""
    editions = load_editions(editions_dir)
    if not editions:
        raise ValueError(f"no editions in {editions_dir}")
    site = PaperSite(**site.model_dump(), publication=paper_name)
    env = _env()
    _prepare_out(out)
    shutil.copytree(STATIC, out / "static")
    ver = _asset_version()
    latest = editions[-1]
    common = {"site": site, "v": ver, "latest": latest, "edition_path": edition_path}
    pages: list[Page] = []

    def write(file: str, template: str, path: str | None, **ctx: object) -> None:
        target = out / file
        target.parent.mkdir(parents=True, exist_ok=True)
        html = env.get_template(template).render(**common, page_path=path, **ctx)
        target.write_text(html, encoding="utf-8", newline="\n")
        if path is not None:
            pages.append(Page(path, file))

    for idx, e in enumerate(editions):
        prev = editions[idx - 1] if idx > 0 else None
        nxt = editions[idx + 1] if idx + 1 < len(editions) else None
        write(
            f"editions/{e.date.isoformat()}/index.html",
            "edition.html.j2",
            edition_path(e),
            e=e,
            prev=prev,
            next=nxt,
            canonical=site.url(edition_path(e)),
        )
    write(
        "index.html",
        "edition.html.j2",
        "/",
        e=latest,
        prev=editions[-2] if len(editions) > 1 else None,
        next=None,
        canonical=site.url(edition_path(latest)),
    )
    write(
        "archive/index.html",
        "archive.html.j2",
        "/archive/",
        editions=list(reversed(editions)),
        canonical=site.url("/archive/"),
    )
    write("about/index.html", "about.html.j2", "/about/", canonical=site.url("/about/"))
    write("404.html", "404.html.j2", None, canonical=None)
    feed = [(e, _feed_html(e)) for e in reversed(editions[-20:])]
    write("feed.xml", "feed.xml.j2", None, entries=feed)
    sitemap = [p for p in pages if p.path != "/"]
    write("sitemap.xml", "sitemap.xml.j2", None, pages=sitemap, lastmod=latest.date)
    write("robots.txt", "robots.txt.j2", None)
    return pages
